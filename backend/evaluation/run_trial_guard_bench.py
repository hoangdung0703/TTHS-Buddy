"""Guard bench for "Phiên tòa giả định" (nhóm B): N full Người xem hearings on ONE fixed case, to count
what the AI-output guards reject and why, before and after a guard change.

What is fixed, so two runs compare like for like:
- the case: crime, khoản, knobs and seed are constants below (FIXED_*); the case is generated by
  Gemini ONCE and cached in --out/case.json, every later run (baseline and after) replays that exact
  file. Delete the cache only to start a new series.
- the legal pack: built from ingestion/chunks.json (the payloads Qdrant holds), no network;
- the role: Người xem by default, so every slot is an AI slot and no scripted student text is involved;
  --role bi_cao answers every question with a fixed line (no LLM) to check that role end to end;
- the optional legal-team style card is switched off (it lives in data/private/, absent in production).
What stays random: every hearing utterance, the nghị án decision and the tuyên án text (Gemini at the
production temperatures), hence the guard outcomes this bench measures.

Output (all under --out, which must be OUTSIDE the repository; nothing is printed but numbers):
- runs/<label>.json: per session - calls, tokens, rejected calls by reason (Rule 9, verdict guard per
  code, money guard unknown_amount, name, other), guard pauses, breaker state, verdict guard codes
  (hard and soft) of every nghị án attempt;
- transcripts/<label>_<n>.jsonl: the whole hearing, for offline replays of a later guard;
- rejections/<label>.jsonl: every hard rejection (text, codes, automatic right/wrong/review);
- money/<label>.jsonl: one line per amount the money guard caught: the amount as written, the
  sentence holding it, the valid amounts of the case at that moment and an automatic category
  (a invented, b same value written differently, c derived from case amounts, d other). Session
  content: never print it, never commit it;
- verdicts/<label>.jsonl: every nghị án decision (structured fields only), so a later guard can be
  replayed on them offline;
- ledger.json: Gemini HTTP calls made by every run of this bench (the series budget).

Budget: every Gemini HTTP request goes through a counter. The run refuses to start when the ledger
plus --sessions x --per-session-cap would pass --series-cap, stops when its own cap is reached, and
stops at once on HTTP 402/429 (the client's internal retry is disabled here, so one request = one
call). Estimate: ~16-22 calls per session (14 AI slots + regenerations), +1-3 for the first case.

Usage (from backend/):
    ../.venv/bin/python -m evaluation.run_trial_guard_bench --out <dir outside repo> --label baseline --sessions 2
"""
