def verdict_code(message: str) -> str:
    if message.startswith("verdict:"):
        return message.split(":", 2)[1]
    if message.startswith("soft:"):
        return message
    if message == "penalty_unchecked":
        return "flag:penalty_unchecked"
    return next((code for needle, code in _OLD_VERDICT_CODES if needle in message), "unmapped")


def session_metrics(ctx: TrialContext, pauses: list[dict], status: str) -> dict:
    records = ctx.recorder.records
    rejected = [r for r in records if not r.accepted]
    by_reason: Counter = Counter()
    verdict_codes: Counter = Counter()
    for record in records:
        if record.call_type == "verdict":
            for v in record.guard_violations:
                verdict_codes[verdict_code(v)] += 1
            if not record.accepted:
                by_reason.update({f"verdict:{verdict_code(v)}" for v in record.guard_violations
                                  if not v.startswith(("soft:", "penalty_unchecked"))} or {"verdict:schema"})
            continue
        if not record.accepted:
            by_reason.update({reason_of(v) for v in record.guard_violations if trial_turn_service._is_hard(v)}
                             or {"other:unknown"})
    return {
        "status": status,
        "calls": len(records),
        "prompt_tokens": sum(r.prompt_tokens for r in records),
        "output_tokens": sum(r.output_tokens for r in records),
        "thinking_tokens": sum(r.thinking_tokens for r in records),
        "rejected_calls": len(rejected),
        "regenerations_by_reason": dict(sorted(by_reason.items())),
        "rejected_by_slot": dict(Counter(r.slot for r in rejected)),
        "verdict_attempt_codes": dict(sorted(verdict_codes.items())),
        "pauses": len(pauses),
        "pause_slots": [p["slot"] for p in pauses],
        "pause_reasons": [sorted({reason_of(v) for v in p["violations"]}) for p in pauses],
        "breaker_tripped": status == "breaker",
        "utterance_flags": dict(Counter(f.split(":")[0] for u in ctx.transcript for f in u.guard_flags)),
        "verdict_flags": list(ctx.verdict_flags),
    }


# Bị cáo (--role bi_cao): fixed answers, no LLM. Every question is answered the same way; the optional
# turns of steps 7-8 are skipped. Enough to check the role still runs through all 11 steps.
DEFENDANT_ANSWER = ("Dạ thưa Hội đồng xét xử, bị cáo xin trình bày đúng như lời khai trong hồ sơ, bị cáo không có "
                    "ý kiến gì thêm.")


def _student_turn(ctx: TrialContext) -> None:
    state = ctx.state
    slot = current_slot(state)
    if state.user_role == "nguoi_xem" or slot is None:
        ctx.state = apply_user_action(state, UserAction("advance", state.current_step, state.version,
                                                        target_step=state.current_step + 1)).state
        return
    if is_interleaved(slot, state.user_role):
        first_identity = slot.key == "khai_mac" and state.slot_user_turns == 0
        text = identity_prefill(ctx.case) if first_identity else DEFENDANT_ANSWER
        apply_student_action(ctx, UserAction("speak", state.current_step, state.version, text=text))
    elif "end_slot" in allowed_actions(state):
        apply_student_action(ctx, UserAction("end_slot", state.current_step, state.version))
    else:
        raise RuntimeError(f"unscripted student slot {slot.key}")


async def play(ctx: TrialContext, pauses: list[dict]) -> str:
    consecutive = 0
    while ctx.state.status == "active":
        if awaiting(ctx.state) == "ai":
            try:
                await run_until_user(ctx)
                consecutive = 0
            except TrialGuardFailure as failure:
                pauses.append({"slot": failure.slot, "violations": [v.split(":")[0] for v in failure.violations]})
                consecutive += 1
                if consecutive >= BREAKER_PAUSES:
                    return "breaker"
            continue
        _student_turn(ctx)
    return ctx.state.status


async def load_or_create_case(out: Path, settings, pack: LegalPack) -> CaseFile:
    cache = out / "case.json"
    if cache.exists():
        return CaseFile.model_validate_json(cache.read_text(encoding="utf-8"))
    recorder = TrialCallRecorder()
    creation = await create_case(FIXED_OPTIONS, settings, None, recorder, pack=pack, seed=FIXED_SEED,
                                 today=FIXED_HEARING_DATE, knobs=FIXED_KNOBS)
    cache.write_text(creation.case.model_dump_json(indent=1), encoding="utf-8")
    return creation.case


def _ledger(out: Path) -> dict:
    path = out / "ledger.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"runs": []}


def _save_ledger(out: Path, ledger: dict) -> None:
    (out / "ledger.json").write_text(json.dumps(ledger, indent=1), encoding="utf-8")


async def main(args: argparse.Namespace) -> int:
    configure_logging("test")   # INFO with redaction, never DEBUG
    out: Path = args.out.resolve()
    if out == REPO_ROOT or REPO_ROOT in out.parents:
        print("STOP: --out must be outside the repository (session content is written there)")
        return 2
    out.mkdir(parents=True, exist_ok=True)
    ledger = _ledger(out)
    spent = sum(r["calls"] for r in ledger["runs"])
    wanted = args.sessions * args.per_session_cap + (0 if (out / "case.json").exists() else 3)
    run_cap = min(wanted, args.series_cap - spent)
    if run_cap < args.per_session_cap:
        print(json.dumps({"stop": "series budget", "spent": spent, "left": args.series_cap - spent,
                          "series_cap": args.series_cap}))
        return 2

    settings = get_settings()
    trial_turn_service.STYLE_CARD_PATH = out / "no-style-card.md"   # never read data/private/
    meter = CallMeter(cap=run_cap)
    meter.install()
    catcher = MoneyCatcher(out / "money" / f"{args.label}.jsonl")
    catcher.install()
    verdict_path = out / "verdicts" / f"{args.label}.jsonl"
    verdict_path.parent.mkdir(parents=True, exist_ok=True)
    (out / "runs").mkdir(exist_ok=True)

    pack = build_local_pack(FIXED_OPTIONS.crime_key)
    sessions: list[dict] = []
    stop: str | None = None
    try:
        case = await load_or_create_case(out, settings, pack)
        shape = CaseShape(case.options.victim_present, case.options.witness_count, case.options.has_related_party)
        for index in range(1, args.sessions + 1):
            catcher.session = index
            ctx = TrialContext(case=case, pack=pack, state=new_session(args.role, shape), settings=settings,
                               recorder=TrialCallRecorder())
            pauses: list[dict] = []
            status = "error"
            try:
                status = await play(ctx, pauses)
            except BudgetStop:
                status, stop = "budget_stop", "run cap"
            except httpx.HTTPStatusError as error:
                status = f"http_{error.response.status_code}"
                if error.response.status_code in (402, 429):
                    stop = status
            finally:
                catcher.flush()
                verdict_records = [r for r in ctx.recorder.records if r.call_type == "verdict"]
                sessions.append({"session": index, **session_metrics(ctx, pauses, status),
                                 "verdict_attempts": len(verdict_records)})
                if ctx.verdict is not None:
                    with verdict_path.open("a", encoding="utf-8") as fh:
                        fh.write(json.dumps({"session": index, "verdict": json.loads(
                            ctx.verdict.model_dump_json(exclude={"reasoning_summary"}))}, ensure_ascii=False) + "\n")
            if stop:
                break
    except CaseGenerationFailed as failure:
        stop = f"case generation failed {failure.error_counts}"
    except httpx.HTTPStatusError as error:
        stop = f"http_{error.response.status_code}"
    finally:
        ledger["runs"].append({"label": args.label, "calls": meter.used})
        _save_ledger(out, ledger)

    money_rows = [json.loads(line) for line in catcher.path.read_text(encoding="utf-8").splitlines()] \
        if catcher.path.exists() else []
    report = {
        "label": args.label, "role": args.role, "stop": stop, "gemini_calls_this_run": meter.used,
        "gemini_calls_series": sum(r["calls"] for r in ledger["runs"]),
        "sessions": sessions,
        "money_categories": dict(Counter(r["category"] for r in money_rows)),
        "money_by_slot": dict(Counter(r["slot"] for r in money_rows)),
    }
    (out / "runs" / f"{args.label}.json").write_text(json.dumps(report, ensure_ascii=False, indent=1),
                                                     encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=1))   # numbers and codes only
    return 0 if stop is None else 1


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, type=Path, help="output directory OUTSIDE the repository")
    parser.add_argument("--label", required=True)
    parser.add_argument("--sessions", type=int, default=2)
    parser.add_argument("--role", choices=("nguoi_xem", "bi_cao"), default="nguoi_xem")
    parser.add_argument("--per-session-cap", type=int, default=28)
    parser.add_argument("--series-cap", type=int, default=90, help="hard cap on calls across every run in --out")
    sys.exit(asyncio.run(main(parser.parse_args())))
