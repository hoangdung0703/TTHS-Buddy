# A hearing pauses on a hard guard failure; the student may press "Thử lại". The bench retries the
# same way and gives up after this many consecutive pauses (the server's circuit breaker is 3).
BREAKER_PAUSES = 3
_SENTENCE_END = re.compile(r"(?<=[.!?;:\n])")


class BudgetStop(Exception):
    pass


@dataclass
class CallMeter:
    """Counts Gemini HTTP requests; one request is one call because the retry loop is disabled."""
    cap: int
    used: int = 0

    def install(self) -> None:
        original = gemini_client._post_with_retry

        def counted(url: str, api_key: str, body: dict, **kwargs) -> httpx.Response:
            if self.used >= self.cap:
                raise BudgetStop(f"run cap {self.cap} reached")
            self.used += 1
            kwargs["max_attempts"] = 1   # no retry: a 402/429 must stop the bench, not be retried
            return original(url, api_key, body, **kwargs)

        gemini_client._post_with_retry = counted


@dataclass
class MoneyCatcher:
    """Wraps the turn service's utterance check: for every unknown_amount it writes the amount as
    written, its sentence and the valid amounts to a file. Content goes to the file only."""
    path: Path
    session: int = 0
    rows: list[dict] = field(default_factory=list)

    def install(self) -> None:
        original = trial_turn_service._check_utterance

        def wrapped(ctx, speaker_id, text, allowed, mode="lenient", pack=None, *, as_student=False,
                    extra_amounts=frozenset()):
            violations, flags = original(ctx, speaker_id, text, allowed, mode, pack, as_student=as_student,
                                         extra_amounts=extra_amounts)
            if "unknown_amount" in violations:
                self._record(ctx, speaker_id, text, pack, extra_amounts)
            return violations, flags

        trial_turn_service._check_utterance = wrapped

    def _record(self, ctx, speaker_id: str, text: str, pack: LegalPack | None, extra: frozenset[int]) -> None:
        case_amounts, _ = trial_turn_service._known_numbers(ctx)
        valid = set(case_amounts) | set(extra)
        legal = set()
        if speaker_id in trial_turn_service.LEGAL_SPEAKER_IDS and pack is not None:
            legal = {parse_money(m.group(1)) for a in pack.articles.values() for m in MONEY_PATTERN.finditer(a.text)}
        slot = ctx.recorder.records[-1].slot if ctx.recorder.records else "?"
        for match in MONEY_PATTERN.finditer(text):
            value = parse_money(match.group(1))
            if value in valid or value in legal:
                continue
            self.rows.append({
                "session": self.session, "slot": slot, "speaker": speaker_id, "written": match.group(0),
                "value": value, "sentence": _sentence_around(text, match.start(), match.end()),
                "valid_case_amounts": sorted(case_amounts), "valid_extra": sorted(extra),
                "category": classify_amount(value, case_amounts, ctx),
            })

    def flush(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.path.open("a", encoding="utf-8") as out:
            for row in self.rows:
                out.write(json.dumps(row, ensure_ascii=False) + "\n")
        self.rows.clear()


def _sentence_around(text: str, start: int, end: int) -> str:
    left = max((m.start() for m in _SENTENCE_END.finditer(text, 0, start)), default=0)
    right = next((m.start() for m in _SENTENCE_END.finditer(text, end)), len(text))
    return text[left:right].strip()


def classify_amount(value: int, case_amounts: set[int], ctx) -> str:
    """a: invented; b: a case amount written differently (parse mismatch); c: derived from two case
    amounts (sum, difference) or a whole percentage of one; d: other known-legal amounts. The labels
    carry the sub-reason so the counts can be reported without the text."""
    amounts = sorted(a for a in case_amounts if a)
    for a in amounts:
        if value * 1000 == a or value == a * 1000 or value * 10 == a or value == a * 10:
            return "b:scale"
    for i, a in enumerate(amounts):
        for b in amounts[i:]:
            if value == a + b:
                return "c:sum"
            if value == abs(a - b) and a != b:
                return "c:difference"
    for a in amounts:
        for pct in range(1, 100):
            if value * 100 == a * pct:
                return "c:percent"
    full_pack_amounts = {parse_money(m.group(1)) for art in ctx.pack.articles.values()
                         for m in MONEY_PATTERN.finditer(art.text)}
    if value in full_pack_amounts:
        return "d:law_amount_outside_slice"
    if value in (200_000, 300_000):
        return "d:court_fee"
    return "a:invented"


def build_local_pack(crime_key: str) -> LegalPack:
    request = pack_request_for_crime(get_crime(crime_key))
    wanted = {(doc, d) for doc, numbers in request.items() for d in numbers}
    chunks = json.loads(CHUNKS_PATH.read_text(encoding="utf-8"))
    pack = build_pack(c for c in chunks if c.get("source_type", "legal_text") == "legal_text"
                      and not c.get("is_repealed") and (c["source_document"], c["dieu_number"]) in wanted)
    if missing_keys(pack, request):
        raise RuntimeError("legal pack incomplete")
    return pack


def reason_of(violation: str) -> str:
    head = violation.split(":")[0]
    if head == "citation" or head == "lay_citation":
        return "rule9"
    if head == "unknown_amount":
        return "money_unknown_amount"
    if head in ("invented_name", "unknown_placeholder"):
        return "name"
    if head == "verdict":
        return "verdict:" + violation.split(":", 2)[1]
    return "other:" + head


